package gen

import (
	"runtime/debug"
	"testing"
)

func TestVersionOf(t *testing.T) {
	zp := func(version string, replace *debug.Module) debug.Module {
		return debug.Module{Path: modulePath, Version: version, Replace: replace}
	}
	dep := func(m debug.Module) *debug.Module { return &m }
	for _, c := range []struct {
		name string
		info debug.BuildInfo
		want string
	}{
		{"main module", debug.BuildInfo{Main: zp("v0.2.0", nil)}, "v0.2.0"},
		{"main module pseudo-version", debug.BuildInfo{Main: zp("v0.0.0-20261101000000-0123456789ab", nil)}, "v0.0.0-20261101000000-0123456789ab"},
		{"main module from a checkout", debug.BuildInfo{Main: zp("(devel)", nil)}, "(devel)"},
		{"main module without version", debug.BuildInfo{Main: zp("", nil)}, "(devel)"},
		{"dependency", debug.BuildInfo{Main: debug.Module{Path: "example.com/tool", Version: "v1.0.0"}, Deps: []*debug.Module{{Path: "zeroparse.dev/zp/runtime", Version: "v0.9.0"}, dep(zp("v0.3.1", nil))}}, "v0.3.1"},
		{"replaced dependency", debug.BuildInfo{Main: debug.Module{Path: "example.com/tool"}, Deps: []*debug.Module{dep(zp("v0.3.1", &debug.Module{Path: "../zp"}))}}, "(devel)"},
		{"no zeroparse module", debug.BuildInfo{Main: debug.Module{Path: "example.com/tool", Version: "v1.0.0"}}, "(devel)"},
	} {
		if got := versionOf(&c.info); got != c.want {
			t.Errorf("%s: %q, want %q", c.name, got, c.want)
		}
	}
}

func TestIsGenerated(t *testing.T) {
	for _, c := range []struct {
		data string
		want bool
	}{
		{HeaderFor("v0.2.0") + "\n\npackage p\n", true},
		{HeaderFor("(devel)"), true},
		{HeaderFor("v0.2.0") + "\r\n\r\npackage p\r\n", true},
		{"// Code generated by zp v0.2.0.\n", false},
		{"// Code generated by other v1. DO NOT EDIT.\n", false},
		{"package p\n// Code generated by zp v0.2.0. DO NOT EDIT.\n", false},
	} {
		if got := IsGenerated([]byte(c.data)); got != c.want {
			t.Errorf("IsGenerated(%q) = %v, want %v", c.data, got, c.want)
		}
	}
}
