package gen

import (
	"bytes"
	"runtime/debug"
	"sync"
)

// modulePath is the module whose version is the generator version.
const modulePath = "zeroparse.dev/zp"

// develVersion is the generator version of a build that has no module version, such as a build
// from a checkout with go run or go test.
const develVersion = "(devel)"

// Version returns the generator version: the version of the module zeroparse.dev/zp in the
// running binary, whether it is the main module (the zp command) or a dependency (a program that
// uses package zeroparse.dev/zp/gen). A build without a module version, or with the module
// replaced, reports "(devel)".
var Version = sync.OnceValue(func() string {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return develVersion
	}
	return versionOf(info)
})

func versionOf(info *debug.BuildInfo) string {
	m := &info.Main
	if m.Path != modulePath {
		m = nil
		for _, d := range info.Deps {
			if d.Path == modulePath {
				m = d
				break
			}
		}
	}
	if m == nil || m.Replace != nil || m.Version == "" {
		return develVersion
	}
	return m.Version
}

// HeaderPrefix starts the header of every generated file, whatever the version of the generator
// that wrote it.
const HeaderPrefix = "// Code generated by zp "

// Header returns the first line of every generated Go and TypeScript file, which names the
// generator version so that a parser can be traced to the generator that produced it. It matches
// the form that marks generated Go files (^// Code generated .* DO NOT EDIT\.$) and is the same in
// every generation by one version, so regeneration is reproducible.
func Header() string {
	return HeaderFor(Version())
}

// HeaderFor returns the header of a file generated by the given generator version.
func HeaderFor(version string) string {
	return HeaderPrefix + version + ". DO NOT EDIT."
}

// IsGenerated reports whether data starts with the header of a generated file.
func IsGenerated(data []byte) bool {
	line, _, _ := bytes.Cut(data, []byte("\n"))
	line = bytes.TrimSuffix(line, []byte("\r"))
	return bytes.HasPrefix(line, []byte(HeaderPrefix)) && bytes.HasSuffix(line, []byte(". DO NOT EDIT."))
}
